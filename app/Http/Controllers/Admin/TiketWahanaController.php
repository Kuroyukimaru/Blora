<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use Illuminate\Http\Request;
use App\Models\TiketWahana;

class TiketWahanaController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | INDEX
    |--------------------------------------------------------------------------
    */

    public function index()
    {
        $tiketWahanas = TiketWahana::latest()->get();

        return view(
            'admin.tiket-wahana.index',
            compact('tiketWahanas')
        );
    }

    /*
    |--------------------------------------------------------------------------
    | CREATE
    |--------------------------------------------------------------------------
    */

    public function create()
    {
        return view(
            'admin.tiket-wahana.create'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | STORE
    |--------------------------------------------------------------------------
    */

    public function store(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | VALIDATION
        |--------------------------------------------------------------------------
        */

        $request->validate([

            'wahana' => 'required|string|max:255',

            'ketentuan' => 'nullable|string',

            'harga' => 'required',
        ]);

        /*
        |--------------------------------------------------------------------------
        | FORMAT HARGA
        |--------------------------------------------------------------------------
        */

        $harga = str_replace(
            '.',
            '',
            $request->harga
        );

        /*
        |--------------------------------------------------------------------------
        | INSERT DATA
        |--------------------------------------------------------------------------
        */

        TiketWahana::create([

            'wahana' => $request->wahana,

            'ketentuan' => $request->ketentuan,

            'harga' => $harga,
        ]);

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return redirect('/admin/tiket-wahana')
            ->with(
                'success',
                'Tiket wahana berhasil ditambahkan'
            );
    }

    /*
    |--------------------------------------------------------------------------
    | EDIT
    |--------------------------------------------------------------------------
    */

    public function edit($id)
    {
        $tiketWahana = TiketWahana::findOrFail($id);

        return view(
            'admin.tiket-wahana.edit',
            compact('tiketWahana')
        );
    }

    /*
    |--------------------------------------------------------------------------
    | UPDATE
    |--------------------------------------------------------------------------
    */

    public function update(Request $request, $id)
    {
        /*
        |--------------------------------------------------------------------------
        | FIND DATA
        |--------------------------------------------------------------------------
        */

        $tiketWahana = TiketWahana::findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | VALIDATION
        |--------------------------------------------------------------------------
        */

        $request->validate([

            'wahana' => 'required|string|max:255',

            'ketentuan' => 'nullable|string',

            'harga' => 'required',
        ]);

        /*
        |--------------------------------------------------------------------------
        | FORMAT HARGA
        |--------------------------------------------------------------------------
        */

        $harga = str_replace(
            '.',
            '',
            $request->harga
        );

        /*
        |--------------------------------------------------------------------------
        | UPDATE DATA
        |--------------------------------------------------------------------------
        */

        $tiketWahana->update([

            'wahana' => $request->wahana,

            'ketentuan' => $request->ketentuan,

            'harga' => $harga,
        ]);

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return redirect('/admin/tiket-wahana')
            ->with(
                'success',
                'Tiket wahana berhasil diupdate'
            );
    }

    /*
    |--------------------------------------------------------------------------
    | DELETE
    |--------------------------------------------------------------------------
    */

    public function destroy($id)
    {
        /*
        |--------------------------------------------------------------------------
        | FIND DATA
        |--------------------------------------------------------------------------
        */

        $tiketWahana = TiketWahana::findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | DELETE
        |--------------------------------------------------------------------------
        */

        $tiketWahana->delete();

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return redirect('/admin/tiket-wahana')
            ->with(
                'success',
                'Tiket wahana berhasil dihapus'
            );
    }
}